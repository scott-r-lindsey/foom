import type { ManifestChannel } from "../../../shared/agent-manifest-v2";
import { orderedObserverFiles } from "../ordered-observer";

function quote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}
export function observerInvocation(
  script: string,
  args: readonly string[],
  windows: boolean,
  stable: boolean,
): { command: string; argv: string[] } {
  const argv = windows
    ? [
        "powershell.exe",
        "-NoProfile",
        "-NonInteractive",
        "-ExecutionPolicy",
        "Bypass",
        "-File",
        script,
        ...args,
      ]
    : ["sh", script, ...args];
  const invocation = `& '${script.replaceAll("'", "''")}'${args.map((arg) => ` ${/^[A-Za-z][A-Za-z0-9_-]*$/u.test(arg) ? arg : `'${arg.replaceAll("'", "''")}'`}`).join("")}`;
  const command = windows
    ? stable || /[%!&|<>^$`]/u.test(script)
      ? `powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand ${Buffer.from(invocation, "utf16le").toString("base64")}`
      : `powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "${script}"${args.map((arg) => ` ${/^[A-Za-z][A-Za-z0-9_-]*$/u.test(arg) ? arg : quote(arg)}`).join("")}`
    : `sh ${quote(script)}${args.map((arg) => ` ${/^[A-Za-z][A-Za-z0-9_-]*$/u.test(arg) ? arg : quote(arg)}`).join("")}`;
  return { command, argv };
}
/** Reuse Foom's native ABIs; only fixed transport options can change generated bytes. */
export function observerAssets(channel: ManifestChannel, windows: boolean): Record<string, string> {
  const options = channel.observer;
  if (options.transport === "external") return {};
  if (options.protocol === "ordered-v2") return orderedObserverFiles();
  let source: string;
  let worker: string | undefined;
  if (!windows) {
    const timeout = String(options.timeoutMs / 1000);
    const sequence = options.sequence
      ? `
[ -n "$FOOM_HOOK_ORDER" ] || exit 0
mkdir "$FOOM_HOOK_ORDER.lock" 2>/dev/null || exit 0
trap 'rmdir "$FOOM_HOOK_ORDER.lock" 2>/dev/null' 0
sequence=$(cat "$FOOM_HOOK_ORDER" 2>/dev/null) || exit 0
case "$sequence" in ''|*[!0-9]*|0?*) exit 0 ;; esac
[ "$sequence" -lt 2147483647 ] 2>/dev/null || exit 0
sequence=$((sequence + 1))
printf '%s' "$sequence" > "$FOOM_HOOK_ORDER" || exit 0
rmdir "$FOOM_HOOK_ORDER.lock" 2>/dev/null || exit 0
trap - 0
`
      : "";
    const input =
      options.transport === "stdin"
        ? "payload=$(head -c 65537) || exit 0"
        : "for payload do :; done";
    const variable = `FOOM_CHANNEL_${channel.id.replaceAll("-", "_")}`;
    const send = `printf '%s' "$payload" | curl -q --noproxy '*' --connect-timeout 1 --max-time ${timeout} --silent --output /dev/null \\
 --request POST --header 'Content-Type: application/json' \\
 --header "Authorization: $FOOM_TOKEN" --header "X-Foom-Session: $FOOM_SESSION" \\
 --header "X-Foom-Channel: $${variable}" --header "X-Foom-Event: $event" ${options.sequence ? '--header "X-Foom-Sequence: $sequence"' : ""} --data-binary @- "$FOOM_HOOK_URL"`;
    source = `#!/bin/sh
${options.response === "empty-json-first" ? "printf '{}\\n'" : ""}
[ -n "$FOOM_HOOK_URL" ] && [ -n "$FOOM_SESSION" ] && [ -n "$FOOM_TOKEN" ] || exit 0
event=""
${options.transport === "stdin" ? `if [ "$#" -gt ${String(options.commandArguments.length)} ]; then for event do :; done; fi` : ""}
${sequence}
${input}
[ "\${#payload}" -le 65536 ] || exit 0
${options.delivery === "detached" ? `(${send}) </dev/null >/dev/null 2>&1 &` : `{ ${send}; } >/dev/null 2>&1`}
exit 0
`;
  } else {
    if (options.delivery === "detached") {
      const files = orderedObserverFiles();
      source = files["observer.ps1"] ?? "";
      worker = files["send.ps1"];
      source = source.replace(
        "if ($args.Count -ne 1 -or $args[0] -notin @('PreInvocation','PostToolUse','Stop')) { exit 0 }",
        () =>
          `$event = if ($args.Count -gt ${String(options.commandArguments.length)}) { $args[${String(options.commandArguments.length)}] } else { 'FoomEvent' }\nif ($event -notmatch '^[A-Za-z][A-Za-z0-9_-]{0,63}$') { exit 0 }`,
      );
      source = source.replace("$args[0], $sequence, $payload", "$event, $sequence, $payload");
      if (!options.sequence) {
        const begin = source.indexOf("  $order =");
        const end = source.indexOf("  [Console]::InputEncoding", begin);
        source = source.slice(0, begin) + "  $sequence = 0\n" + source.slice(end);
        source = source.replace("if (!$env:FOOM_HOOK_ORDER) { exit 0 }", "");
      }
      if (options.response === "silent")
        source = source
          .replace("[Console]::Out.WriteLine('{}')", "")
          .replace("[Console]::Out.Flush()", "");
    } else {
      const fixed = orderedObserverFiles()["observer.ps1"] ?? "";
      const order = options.sequence
        ? fixed.slice(fixed.indexOf("  $order ="), fixed.indexOf("  [Console]::InputEncoding"))
        : "";
      source = `# Foom observe-only transport. No agent data is executable.
${options.response === "empty-json-first" ? "[Console]::Out.WriteLine('{}')\n[Console]::Out.Flush()" : ""}
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
if (!$env:FOOM_HOOK_URL -or !$env:FOOM_SESSION -or !$env:FOOM_TOKEN) { exit 0 }
try {
${order}
  [Console]::InputEncoding = New-Object System.Text.UTF8Encoding($false)
${
  options.transport === "stdin"
    ? `  $buffer = New-Object char[] 65537
  $count = 0
  while ($count -lt $buffer.Length) {
    $read = [Console]::In.Read($buffer, $count, $buffer.Length - $count)
    if ($read -eq 0) { break }
    $count += $read
  }
  if ($count -gt 65536) { exit 0 }
  $payload = [System.String]::new($buffer, 0, $count)`
    : "  $payload = $args[-1]"
}
  if ([System.Text.Encoding]::UTF8.GetByteCount($payload) -gt 65536) { exit 0 }
  $event = if ($args.Count -gt ${String(options.commandArguments.length)} -and ${options.transport === "stdin" ? "$true" : "$false"}) { $args[${String(options.commandArguments.length)}] } else { '' }
  $headers = @{ 'Authorization' = $env:FOOM_TOKEN; 'X-Foom-Session' = $env:FOOM_SESSION; 'X-Foom-Event' = $event${options.sequence ? "; 'X-Foom-Sequence' = [string]$sequence" : ""} }
  $direct = @{}
  if ($PSVersionTable.PSVersion.Major -ge 6) { $direct['NoProxy'] = $true } else { [System.Net.WebRequest]::DefaultWebProxy = New-Object System.Net.WebProxy }
  Invoke-WebRequest @direct -UseBasicParsing -Method Post -Uri $env:FOOM_HOOK_URL -Headers $headers -ContentType 'application/json' -Body ([System.Text.Encoding]::UTF8.GetBytes($payload)) -TimeoutSec ${String(Math.ceil(options.timeoutMs / 1000))} | Out-Null
} catch { }
exit 0
`;
    }
    const variable = `FOOM_CHANNEL_${channel.id.replaceAll("-", "_")}`;
    const addHeader = (text: string) =>
      text.replace(
        "'X-Foom-Session' = $env:FOOM_SESSION",
        `'X-Foom-Session' = $env:FOOM_SESSION; 'X-Foom-Channel' = $env:${variable}`,
      );
    source = addHeader(source);
    if (worker)
      worker = addHeader(worker).replaceAll(
        /-TimeoutSec [13]/gu,
        `-TimeoutSec ${String(Math.ceil(options.timeoutMs / 1000))}`,
      );
    source = source.replaceAll(
      /-TimeoutSec [13]/gu,
      `-TimeoutSec ${String(Math.ceil(options.timeoutMs / 1000))}`,
    );
  }
  source = source.replaceAll("FOOM_HOOK_ORDER", `FOOM_ORDER_${channel.id.replaceAll("-", "_")}`);
  if (windows && options.placement === "launch")
    source = "if ($args.Count -eq 1 -and $args[0] -eq '--foom-probe') { exit 0 }\n" + source;
  return {
    [windows ? "observer.ps1" : "observer.sh"]: source,
    ...(windows && worker ? { "send.ps1": worker } : {}),
  };
}
export function observerVersion(channel: ManifestChannel, windows: boolean): number {
  const version = channel.observer.version;
  return typeof version === "number" ? version : version[windows ? "win32" : "posix"];
}
